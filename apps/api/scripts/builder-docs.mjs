// Copies the CLI pages of the docs site into the assistant's docs tool, so it
// answers CLI questions from what the site says today.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const docs = fileURLToPath(
  new URL('../../website/src/content/docs/', import.meta.url)
);
const out = fileURLToPath(
  new URL('../src/controllers/builder/docs.generated.ts', import.meta.url)
);
const SITE = 'https://ganju.ai';

const read = file => readFileSync(docs + file, 'utf8');
const body = markdown => markdown.replace(/^---\n[\s\S]*?\n---\n/, '');
const section = (markdown, heading) => {
  const start = markdown.indexOf(`\n## ${heading}\n`);
  if (start < 0) throw new Error(`No "## ${heading}" section`);
  const end = markdown.indexOf('\n## ', start + 1);
  return markdown.slice(start + 1, end < 0 ? undefined : end);
};
// Site-relative links become full ones the owner can open.
const absolute = markdown =>
  markdown.replace(/\]\(\/docs\//g, `](${SITE}/docs/`);

const topics = {
  cli: `Page: ${SITE}/docs/tools/cli/\n\n${body(read('tools/cli.md'))}`,
  cli_data: `Page: ${SITE}/docs/data-api/#from-the-command-line\n\n${section(read('data-api.md'), 'From the command line')}`
};

const source = `// Generated by scripts/builder-docs.mjs from the docs site. Don't edit.
export const BUILDER_DOCS = ${JSON.stringify(
  Object.fromEntries(
    Object.entries(topics).map(([key, text]) => [key, absolute(text).trim()])
  ),
  null,
  2
)} as const;
`;

writeFileSync(out, source);
